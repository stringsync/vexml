import { dirname, resolve } from "node:path";
import { type Fs, NodeFs } from "core/system";

/**
 * Where the stub lives. The name is fixed because npm's trusted publisher
 * entry for each package names this file.
 */
export const PUBLISH_WORKFLOW_PATH = ".github/workflows/publish.yml";

/** What a `PublishWorkflow` reads and writes through; the real filesystem by default. */
export interface PublishWorkflowOptions {
	/** The command the job runs to publish, such as `bin/mdom publish`. */
	command: string;
	fs?: Fs;
}

/**
 * The GitHub Actions workflow that publishes a release from a job npm trusts.
 * It is generated and holds no package list: it checks out the release commit
 * and runs the declaration's own publish-only mode, so the `Release` stays the
 * one place that says what ships. Commit it like a lockfile; a release writes
 * it when it is missing or stale, and `check` fails on drift.
 */
export class PublishWorkflow {
	private readonly command: string;
	private readonly fs: Fs;

	constructor(opts: PublishWorkflowOptions) {
		this.command = opts.command;
		this.fs = opts.fs ?? new NodeFs();
	}

	/** The workflow file's whole text. */
	text(): string {
		return `# Generated by mono; do not edit. A release rewrites it when it is stale.
# npm's trusted publisher entries name this file, so keep its path.
name: publish

on:
  workflow_dispatch:
    inputs:
      ref:
        description: The release commit to publish
        required: true

permissions:
  contents: read
  id-token: write

jobs:
  publish:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@v4
        with:
          ref: \${{ inputs.ref }}
      - uses: oven-sh/setup-bun@v2
      - uses: actions/setup-node@v4
        with:
          node-version: 24
          registry-url: https://registry.npmjs.org
      - run: npm install -g npm@latest
      - run: bun install --frozen-lockfile
      - run: ${this.command}
`;
	}

	/** What is wrong with the file under `root`, or `undefined` when it is current. */
	async drift(root: string): Promise<"missing" | "stale" | undefined> {
		const path = resolve(root, PUBLISH_WORKFLOW_PATH);
		if (!(await this.fs.exists(path))) {
			return "missing";
		}
		return (await this.fs.read(path)) === this.text() ? undefined : "stale";
	}

	/** Writes the file under `root` when it is missing or stale; whether it wrote. */
	async write(root: string): Promise<boolean> {
		if ((await this.drift(root)) === undefined) {
			return false;
		}
		const path = resolve(root, PUBLISH_WORKFLOW_PATH);
		await this.fs.mkdir(dirname(path), { recursive: true });
		await this.fs.write(path, this.text());
		return true;
	}

	/** Throws when the file under `root` is missing or stale. */
	async check(root: string): Promise<void> {
		const drift = await this.drift(root);
		if (drift !== undefined) {
			throw new Error(
				`${PUBLISH_WORKFLOW_PATH} is ${drift}: run a release to regenerate it, and commit it`,
			);
		}
	}
}
